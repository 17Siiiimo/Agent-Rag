def target_query(target_table: str, scope: str, sector: str) -> str:
    parts = [target_table.replace("_", " "), scope.replace("_", " "), sector.replace("_", " ")]
    parts += SCOPE_KEYWORDS.get(scope, [])
    parts += TABLE_TITLES.get(target_table, [])
    scope_anchors = scoped_table_signature(sector, scope, target_table)
    parts += scope_anchors
    if not scope_anchors:
        parts += FINANCIAL_ANCHORS.get(sector, {}).get(target_table, [])
    return " ".join(parts)


def keyword_hits(text: str, keywords: list[str]) -> list[str]:
    norm = normalize_text(text)
    loose_norm = _loose_phrase(norm)
    hits: list[str] = []
    for kw in keywords:
        kw_norm = normalize_text(kw)
        if not kw_norm:
            continue
        if kw_norm in norm:
            hits.append(kw)
            continue
        # PDF text extraction often changes punctuation/spacing around apostrophes,
        # dashes, semicolons, and commas. For multi-word row labels, compare an
        # alphanumeric-only phrase too so complete table signatures still dominate.
        if len(kw_norm.split()) >= 2 and _loose_phrase(kw_norm) in loose_norm:
            hits.append(kw)
    return hits


def _loose_phrase(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", normalize_text(text)).strip()
